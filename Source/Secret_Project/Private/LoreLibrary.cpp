bool ULoreLibrary::FindLore(FName LoreId, FLoreEntry& OutEntry)
{
    if (LoreId.IsNone()) return false;
    for (const FLoreEntry& E : GetCatalog())
        if (E.LoreId == LoreId) { OutEntry = E; return true; }
    return false;
}

TArray<FName> ULoreLibrary::GetAllLoreIds()
{
    TArray<FName> Ids;
    for (const FLoreEntry& E : GetCatalog()) Ids.Add(E.LoreId);
    return Ids;
}
