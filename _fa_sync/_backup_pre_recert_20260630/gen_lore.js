const _esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function _inline(s){
  s = _esc(s);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>");
  s = s.replace(/(^|[^*])\*([^*\n]+)\*/g, "$1<i>$2</i>");
  s = s.replace(/`([^`]+)`/g, "<code>$1</code>");
  return s;
}
function _renderTable(rows){
  const cells = rows.map(r => r.trim().replace(/^\|/,"").replace(/\|$/,"").split("|").map(c => c.trim()));
  const sep = cells[1] && cells[1].every(c => /^:?-{2,}:?$/.test(c));
  const start = sep ? 2 : 1;
  let h = "<table><thead><tr>" + cells[0].map(c => `<th>${_inline(c)}</th>`).join("") + "</tr></thead><tbody>";
  for (let r = start; r < cells.length; r++) h += "<tr>" + cells[r].map(c => `<td>${_inline(c)}</td>`).join("") + "</tr>";
  return h + "</tbody></table>";
}
