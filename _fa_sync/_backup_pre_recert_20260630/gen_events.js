const _esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function _inline(s){ s = _esc(s); s = s.replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>"); s = s.replace(/(^|[^*])\*([^*\n]+)\*/g, "$1<i>$2</i>"); s = s.replace(/`([^`]+)`/g, "<code>$1</code>"); return s; }
function _renderTable(rows){ const cells = rows.map(r => r.trim().replace(/^\|/,"").replace(/\|$/,"").split("|").map(c => c.trim())); const sep = cells[1] && cells[1].every(c => /^:?-{2,}:?$/.test(c)); const start = sep ? 2 : 1; let h = "<table><thead><tr>" + cells[0].map(c => `<th>${_inline(c)}</th>`).join("") + "</tr></thead><tbody>"; for (let r = start; r < cells.length; r++) h += "<tr>" + cells[r].map(c => `<td>${_inline(c)}</td>`).join("") + "</tr>"; return h + "</tbody></table>"; }
function _mdToHtml(md){
  const lines = md.split(/\r?\n/); let html = "", lb = [], lt = null, tb = [];
  const fl = () => { if (lb.length){ html += `<${lt}>` + lb.map(x => `<li>${x}</li>`).join("") + `</${lt}>`; lb = []; lt = null; } };
  const ft = () => { if (tb.length){ html += _renderTable(tb); tb = []; } };
  for (const raw of lines){ const line = raw.replace(/\s+$/,""); let m;
    if (/^\s*$/.test(line)){ fl(); ft(); continue; }
    if (/^\s*\|.*\|\s*$/.test(line)){ fl(); tb.push(line); continue; } else ft();
    if (m = line.match(/^(#{1,6})\s+(.*)$/)){ fl(); const lv = Math.min(m[1].length + 1, 6); html += `<h${lv}>${_inline(m[2])}</h${lv}>`; continue; }
    if (/^\s*(---|\*\*\*|___)\s*$/.test(line)){ fl(); html += "<hr>"; continue; }
    if (m = line.match(/^\s*>\s?(.*)$/)){ fl(); html += `<blockquote>${_inline(m[1])}</blockquote>`; continue; }
    if (m = line.match(/^\s*[-*+]\s+(.*)$/)){ if (lt !== "ul"){ fl(); lt = "ul"; } lb.push(_inline(m[1])); continue; }
    if (m = line.match(/^\s*\d+\.\s+(.*)$/)){ if (lt !== "ol"){ fl(); lt = "ol"; } lb.push(_inline(m[1])); continue; }
    fl(); html += `<p>${_inline(line)}</p>`;
  }
  fl(); ft(); return html;
}
