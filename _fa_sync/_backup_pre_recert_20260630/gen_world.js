// ── .md → HTML 주입기 (gen_lore와 동일 — 정본 .md를 제 카테고리로 이전, 2026-06-26) ──
const CANON_DIR = "C:/Secret_Project";
const _esc = s => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
function _inline(s){
  s = _esc(s);
  s = s.replace(/\*\*([^*]+)\*\*/g, "<b>$1</b>");
  s = s.replace(/(^|[^*])\*([^*\n]+)\*/g, "$1<i>$2</i>");
  s = s.replace(/`([^`]+)`/g, "<code>$1</code>");
  return s;
}
function _renderTable(rows){
  const cells = rows.map(r => r.trim().replace(/^\|/,"").replace(/\|$/,"").split("|").map(c => c.trim()));
  const sep = cells[1] && cells[1].every(c => /^:?-{2,}:?$/.test(c));
  const start = sep ? 2 : 1;
  let h = "<table><thead><tr>" + cells[0].map(c => `<th>${_inline(c)}</th>`).join("") + "</tr></thead><tbody>";
  for (let r = start; r < cells.length; r++) h += "<tr>" + cells[r].map(c => `<td>${_inline(c)}</td>`).join("") + "</tr>";
  return h + "</tbody></table>";
}
// ★재조립(2026-06-26): 짧은 산문 토막에 붙은 불필요한 제목 제거 → 흐르는 글. 목록·표 달린 섹션 제목은 보존.
function _deMicroHead(html){
  if (!html) return html;
  const segs = html.split(/(<h[1-6][^>]*>[\s\S]*?<\/h[1-6]>)/);
  let out = segs[0] || "";
  for (let i = 1; i < segs.length; i += 2){
    const head = segs[i], content = segs[i + 1] || "";
    const keep = /class="k"/.test(head);
    const txt = content.replace(/<[^>]+>/g, "").replace(/\s+/g, " ").trim();
    const hasBlock = /<ul>|<ol>|<table>|<blockquote>/.test(content);
    out += (!keep && !hasBlock && txt.length < 300) ? content : head + content;
  }
  return out;
}
function _mdToHtml(md){
  const lines = md.split(/\r?\n/);
  let html = "", lb = [], lt = null, tb = [];
  const fl = () => { if (lb.length){ html += `<${lt}>` + lb.map(x => `<li>${x}</li>`).join("") + `</${lt}>`; lb = []; lt = null; } };
  const ft = () => { if (tb.length){ html += _renderTable(tb); tb = []; } };
  for (const raw of lines){
    const line = raw.replace(/\s+$/,""); let m;
    if (/^\s*$/.test(line)){ fl(); ft(); continue; }
    if (/^\s*\|.*\|\s*$/.test(line)){ fl(); tb.push(line); continue; } else ft();
    if (m = line.match(/^(#{1,6})\s+(.*)$/)){ fl(); const lv = Math.min(m[1].length + 1, 6); html += `<h${lv}>${_inline(m[2])}</h${lv}>`; continue; }
    if (/^\s*(---|\*\*\*|___)\s*$/.test(line)){ fl(); html += "<hr>"; continue; }
    if (m = line.match(/^\s*>\s?(.*)$/)){ fl(); html += `<blockquote>${_inline(m[1])}</blockquote>`; continue; }
    if (m = line.match(/^\s*[-*+]\s+(.*)$/)){ if (lt !== "ul"){ fl(); lt = "ul"; } lb.push(_inline(m[1])); continue; }
    if (m = line.match(/^\s*\d+\.\s+(.*)$/)){ if (lt !== "ol"){ fl(); lt = "ol"; } lb.push(_inline(m[1])); continue; }
    fl(); html += `<p>${_inline(line)}</p>`;
  }
  fl(); ft();
  return html;
}
// list: [fileOrFiles, displayName] → 한 doc. fileOrFiles가 배열이면 여러 .md를 한 doc으로 *병합*(파편화 해소).
function injectMd(list, startOrder){
  const out = [];
  list.forEach((ent, i) => {
    const [files, nm] = ent;
    const fns = Array.isArray(files) ? files : [files];
    const parts = [];
    for (const fn of fns){
      let md;
      try { md = fs.readFileSync(path.join(CANON_DIR, fn), "utf8"); }
      catch (e){ console.warn("  skip(missing):", fn); continue; }
      parts.push(md.trim());
    }
    if (!parts.length) return;
    out.push({ order: startOrder + i, name: nm, description: _mdToHtml(parts.join("\n\n---\n\n")) });
  });
  return out;
}

// 자유텍스트 필드만 사용: description(본문) + spoilerNotes(이면). 태그/숫자/select 필드는 안 건드림.
function buildDump(bpId, outName, dbName, docsIn) {
  const bp = BP(bpId);
  const docs = docsIn.map(c => {
    const merged = {
      name: c.name, parentDoc: "", documentColor: "", documentBackgroundColor: "",
      finishedSwitch: "", minorSwitch: "", deadSwitch: "", categorySwitch: "",
      order: c.order, tags: [], categoryDescription: "", otherNames: c.otherNames || [],
      description: _deMicroHead(c.description || ""),
    };
    if (c.spoilerNotes) merged.spoilerNotes = c.spoilerNotes;
    const extraFields = Object.keys(merged).map(id => ({ id, value: merged[id] }));
    const _id = crypto.randomUUID();
    const doc = {
      extraFields, hierarchicalPath: bp.namePlural, icon: bp.icon, id: _id,
      type: bpId, url: `/project/display-content/${bpId}/${_id}`, _id,
    };
    doc._rev = "1-" + crypto.createHash("md5").update(JSON.stringify(doc)).digest("hex");
    return doc;
  });
  const N = docs.length;
  const header = {
    version: "1.2.8", db_type: "idb", start_time: new Date().toISOString(),
    db_info: { doc_count: N, update_seq: N, idb_attachment_format: "binary", db_name: dbName, auto_compaction: false, adapter: "idb" }
  };
  const dump = JSON.stringify(header) + "\n" + JSON.stringify({ docs }) + "\n" + JSON.stringify({ seq: N }) + "\n";
  const out = path.join(PROJ, outName);
  fs.writeFileSync(out, dump, "utf8");
  console.log(`wrote ${N} docs -> ${out} (${dump.length} bytes)`);
  return dump;
}

